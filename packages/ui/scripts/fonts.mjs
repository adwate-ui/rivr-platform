/**
 * Copies the webfont files RIVR uses out of the @fontsource packages into dist/fonts/ and
 * writes dist/fonts.css with one @font-face per file (docs/decisions/0011).
 *
 * dist/fonts.css sits beside dist/styles.css, so its `url(./fonts/...)` paths are right
 * for both: the Tailwind CLI inlines the file into dist/styles.css unchanged, and the
 * Tailwind Vite plugin (Storybook) rewrites them relative to src/styles.css.
 * Runs before every build and every Storybook start.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

/** The faces, weights and subsets the token typefaces need. Devanagari faces only set Hindi. */
const FACES = [
  { name: 'bodoni-moda', weights: [400], subsets: ['latin', 'latin-ext'] },
  { name: 'instrument-sans', weights: [400, 500, 600], subsets: ['latin', 'latin-ext'] },
  { name: 'tiro-devanagari-hindi', weights: [400], subsets: ['devanagari'] },
  { name: 'noto-sans-devanagari', weights: [400, 500, 600], subsets: ['devanagari'] },
];

// fontsource writes: src: url(./files/x.woff2) format('woff2'), url(./files/x.woff) format('woff');
const SOURCE = /src: url\(\.\/files\/([\w-]+\.woff2)\) format\('woff2'\)[^;]*;/;

/**
 * The @font-face rule for one subset and weight, taken from fontsource's `<weight>.css`
 * (the per-subset files leave out `unicode-range`, which the browser needs to pick the file).
 */
function fontFaceRule(name, subset, weight) {
  const directory = `node_modules/@fontsource/${name}`;
  const blocks = readFileSync(`${directory}/${weight}.css`, 'utf8').split(/(?=\/\* )/);
  const rule = blocks.find((block) => block.startsWith(`/* ${name}-${subset}-${weight}-normal */`));
  const file = rule && SOURCE.exec(rule)?.[1];
  if (!file) throw new Error(`No ${subset} ${weight} woff2 in @fontsource/${name}/${weight}.css`);
  copyFileSync(`${directory}/files/${file}`, `dist/fonts/${file}`);
  return rule.replace(SOURCE, `src: url(./fonts/${file}) format('woff2');`).trim();
}

mkdirSync('dist/fonts', { recursive: true });

const rules = FACES.flatMap(({ name, weights, subsets }) =>
  subsets.flatMap((subset) => weights.map((weight) => fontFaceRule(name, subset, weight))),
);

const header = '/* Generated by packages/ui/scripts/fonts.mjs from the @fontsource packages. Do not edit. */';
writeFileSync('dist/fonts.css', `${header}\n${rules.join('\n\n')}\n`);
