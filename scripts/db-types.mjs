#!/usr/bin/env node
/**
 * `pnpm db:types`: regenerates packages/db/src/database.types.ts from the local database.
 * Run it after every migration; a stale file makes the typecheck lie (CLAUDE.md, "Gotchas").
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { writeSupabaseConfig } from './lib/supabase-config.mjs';
import { localBinary, worktreeRoot } from './lib/worktree.mjs';

const root = worktreeRoot();
writeSupabaseConfig(root);
const types = execFileSync(localBinary('supabase', root), ['gen', 'types', '--lang', 'typescript', '--local'], {
  cwd: root,
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'inherit'],
});
const header = '// Generated by `pnpm db:types` from the local database. Do not edit.\n\n';
writeFileSync(join(root, 'packages/db/src/database.types.ts'), header + types);
process.stdout.write('packages/db/src/database.types.ts updated\n');
